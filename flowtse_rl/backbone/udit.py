class DiTBlock(nn.Module):
    """
    A DiT block with adaptive layer norm zero (adaLN-Zero) conditioning.
    """
    def __init__(self, hidden_size, num_heads, mlp_ratio=4.0, skip=False, skip_norm=True, use_checkpoint=True, **block_kwargs):
        super().__init__()
        self.norm1 = nn.LayerNorm(hidden_size, elementwise_affine=False, eps=1e-6)
        self.attn = Attention(hidden_size, num_heads=num_heads, qkv_bias=True, **block_kwargs)
        self.norm2 = nn.LayerNorm(hidden_size, elementwise_affine=False, eps=1e-6)
        mlp_hidden_dim = int(hidden_size * mlp_ratio)
        approx_gelu = lambda: nn.GELU(approximate="tanh")
        self.mlp = Mlp(in_features=hidden_size, hidden_features=mlp_hidden_dim, act_layer=approx_gelu, drop=0)
        self.adaLN_modulation = nn.Sequential(
            nn.SiLU(),
            nn.Linear(hidden_size, 6 * hidden_size, bias=True)
        )
        self.skip_linear = nn.Linear(2 * hidden_size, hidden_size) if skip else None
        self.skip_norm =  nn.LayerNorm(2 * hidden_size, elementwise_affine=False, eps=1e-6) if skip_norm else nn.Identity()
        self.use_checkpoint = use_checkpoint
        self._compiled_forward = None
    
    def forward(self, x, c, skip=None, token_mask=None, attention_mask=None, compile_masked=False,
                allow_compile=True):
        if (self._compiled_forward is not None and allow_compile and self.training and torch.is_grad_enabled()
                and (compile_masked or (token_mask is None and attention_mask is None))):
            return self._compiled_forward(x, c, skip, token_mask, attention_mask)
        if self.use_checkpoint and self.training and torch.is_grad_enabled():
            return torch.utils.checkpoint.checkpoint(
                self._forward, x, c, skip, token_mask, attention_mask, use_reentrant=False)
        else:
            return self._forward(x, c, skip, token_mask, attention_mask)

    def _forward(self, x, c, skip=None, token_mask=None, attention_mask=None):
        if self.skip_linear is not None:
            cat = torch.cat([x, skip], dim=-1)
            cat = self.skip_norm(cat)
            x = self.skip_linear(cat)
        shift_msa, scale_msa, gate_msa, shift_mlp, scale_mlp, gate_mlp = self.adaLN_modulation(c).chunk(6, dim=1)
        x = x + gate_msa.unsqueeze(1) * self.attn(
            modulate(self.norm1(x), shift_msa, scale_msa), context_mask=token_mask,
            attention_mask=attention_mask)
        x = x + gate_mlp.unsqueeze(1) * self.mlp(modulate(self.norm2(x), shift_mlp, scale_mlp))
        if token_mask is not None:
            x = x.masked_fill(~token_mask[:, :, None], 0)
        return x


class FinalLayer(nn.Module):
    """
    The final layer of DiT.
    """
    def __init__(self, hidden_size, output_dim):
        super().__init__()
        self.norm_final = nn.LayerNorm(hidden_size, elementwise_affine=False, eps=1e-6)
        self.linear = nn.Linear(hidden_size, output_dim, bias=True)
        self.adaLN_modulation = nn.Sequential(
            nn.SiLU(),
            nn.Linear(hidden_size, 2 * hidden_size, bias=True)
        )

    def forward(self, x, c):
        shift, scale = self.adaLN_modulation(c).chunk(2, dim=1)
        x = modulate(self.norm_final(x), shift, scale)
        x = self.linear(x)
        return x


class UDiT(nn.Module):
    """
    Diffusion model with a Transformer backbone, compatible with Mean-flow.
    """
    def __init__(
        self,
        input_dim=256,
        output_dim=128,
        pos_method='none',
        pos_length=500,
        hidden_size=1152,
        depth=28,
        num_heads=16,
        mlp_ratio=4.0,
        use_checkpoint=False,
        mixture_condition_mode='none',
    ):
        super().__init__()
        self.num_heads = num_heads
        self.input_dim = input_dim
        self.mixture_condition_mode = mixture_condition_mode
        if self.mixture_condition_mode not in {'none', 'channel_concat', 'time_prefix'}:
            raise ValueError(
                "mixture_condition_mode must be 'none', 'channel_concat', or 'time_prefix'"
            )

        state_input_dim = input_dim * 2 if self.mixture_condition_mode == 'channel_concat' else input_dim
        self.input_proj = nn.Linear(state_input_dim, hidden_size, bias=True)
        self.enrollment_proj = (
            nn.Linear(input_dim, hidden_size, bias=True)
            if self.mixture_condition_mode == 'channel_concat'
            else None
        )
        self.t_embedder = TimestepEmbedder(hidden_size)
        self.delta_embedder = TimestepEmbedder(hidden_size)
        self.pos_embed = PE_wrapper(dim=hidden_size, method=pos_method, length=pos_length)

        self.in_blocks = nn.ModuleList([
            DiTBlock(hidden_size, num_heads, mlp_ratio=mlp_ratio, use_checkpoint=use_checkpoint) for _ in range(depth // 2)
        ])
        self.mid_block = DiTBlock(hidden_size, num_heads, mlp_ratio=mlp_ratio, use_checkpoint=use_checkpoint)
        self.out_blocks = nn.ModuleList([
            DiTBlock(hidden_size, num_heads, mlp_ratio=mlp_ratio, skip=True, use_checkpoint=use_checkpoint) for _ in range(depth // 2)
        ])
        
        self.final_layer = FinalLayer(hidden_size, output_dim)
        self.initialize_weights()

    def initialize_weights(self):
        # Initialize transformer layers:
        def _basic_init(module):
            if isinstance(module, nn.Linear):
                torch.nn.init.xavier_uniform_(module.weight)
                if module.bias is not None:
                    nn.init.constant_(module.bias, 0)
        self.apply(_basic_init)

        # Initialize patch_embed like nn.Linear (instead of nn.Conv2d):
        nn.init.normal_(self.input_proj.weight, std=0.02)

        # Initialize timestep embedding MLP:
        nn.init.normal_(self.t_embedder.mlp[0].weight, std=0.02)
        nn.init.normal_(self.t_embedder.mlp[2].weight, std=0.02)
        nn.init.normal_(self.delta_embedder.mlp[0].weight, std=0.02)
        nn.init.normal_(self.delta_embedder.mlp[2].weight, std=0.02)

        # Zero-out adaLN modulation layers in DiT blocks:
        for block in self.in_blocks:
            nn.init.constant_(block.adaLN_modulation[-1].weight, 0)
            nn.init.constant_(block.adaLN_modulation[-1].bias, 0)
        
        nn.init.constant_(self.mid_block.adaLN_modulation[-1].weight, 0)
        nn.init.constant_(self.mid_block.adaLN_modulation[-1].bias, 0)
        
        for block in self.out_blocks:
            nn.init.constant_(block.adaLN_modulation[-1].weight, 0)
            nn.init.constant_(block.adaLN_modulation[-1].bias, 0)

        # Zero-out output layers:
        nn.init.constant_(self.final_layer.adaLN_modulation[-1].weight, 0)
        nn.init.constant_(self.final_layer.adaLN_modulation[-1].bias, 0)
        nn.init.constant_(self.final_layer.linear.weight, 0)
        nn.init.constant_(self.final_layer.linear.bias, 0)

    def forward(self, x, t, r, enrollment, mixture=None, valid_mix_frames=None):
        """
        Forward pass of UDiT compatible with Mean-flow.
        
        Args:
            x: (N, C, T) tensor of input signals
            t: (N,) tensor of current diffusion timesteps
            r: (N,) tensor of goal timesteps
            enrollment: (N, C, T_enroll) tensor of enrollment/reference signals
            mixture: optional (N, C, T) observed mixture condition
        
        Returns:
            (N, C, T) tensor of predicted velocities
        """
        # Scale timesteps to [0, 1000] range like in dit.py
        timesteps_t = t * 1000
        timesteps_r = r * 1000
        
        if x.shape[1] != self.input_dim or enrollment.shape[1] != self.input_dim:
            raise ValueError(f"Expected {self.input_dim} feature channels for state and enrollment")
        enrollment_length = enrollment.shape[2]
        mixture_length = 0
        state_mask = token_mask = None
        if valid_mix_frames is not None:
            lengths = torch.as_tensor(valid_mix_frames, device=x.device, dtype=torch.long)
            if lengths.shape != (x.shape[0],) or torch.any(lengths <= 0) or torch.any(lengths > x.shape[-1]):
                raise ValueError('valid_mix_frames must contain actual positive frame counts')
            state_mask = torch.arange(x.shape[-1], device=x.device)[None] < lengths[:, None]
            x = x.masked_fill(~state_mask[:, None], 0)
            if mixture is not None:
                mixture = mixture.masked_fill(~state_mask[:, None], 0)
            prefix_mask = torch.ones((x.shape[0], enrollment_length), device=x.device, dtype=torch.bool)
            if self.mixture_condition_mode == 'time_prefix':
                # Its rotary positions depend on the prefix length. Ragged
                # time-prefix conditioning is outside the v0 mixture-start path.
                if torch.any(lengths != x.shape[-1]):
                    raise ValueError('Ragged time-prefix conditioning is unsupported')
                prefix_mask = torch.cat((prefix_mask, state_mask), dim=1)
            token_mask = torch.cat((prefix_mask, state_mask), dim=1)
        if self.mixture_condition_mode == 'channel_concat':
            if mixture is None:
                raise ValueError("channel_concat requires a mixture condition")
            if mixture.shape[:2] != x.shape[:2] or mixture.shape[2] != x.shape[2]:
                raise ValueError(
                    f"mixture condition shape {tuple(mixture.shape)} must match state shape {tuple(x.shape)}"
                )
            enrollment_tokens = self.enrollment_proj(enrollment.transpose(2, 1))
            state_tokens = self.input_proj(torch.cat((x, mixture), dim=1).transpose(2, 1))
            x = torch.cat((enrollment_tokens, state_tokens), dim=1)
        elif self.mixture_condition_mode == 'time_prefix':
            if mixture is None:
                raise ValueError("time_prefix requires a mixture condition")
            if mixture.shape[:2] != x.shape[:2] or mixture.shape[2] != x.shape[2]:
                raise ValueError(
                    f"mixture condition shape {tuple(mixture.shape)} must match state shape {tuple(x.shape)}"
                )
            mixture_length = mixture.shape[2]
            x = torch.cat((enrollment, mixture, x), dim=-1)
            x = self.input_proj(x.transpose(2, 1))
        else:
            x = torch.cat((enrollment, x), dim=-1)
            x = self.input_proj(x.transpose(2, 1))

        # x is now (N, T, hidden_size).
        if token_mask is not None:
            x = x.masked_fill(~token_mask[:, :, None], 0)
        x = self.pos_embed(x)
        
        # Prepare timestep inputs
        if not torch.is_tensor(timesteps_t):
            timesteps_t = torch.tensor([timesteps_t], dtype=torch.long, device=x.device)
        elif torch.is_tensor(timesteps_t) and len(timesteps_t.shape) == 0:
            timesteps_t = timesteps_t[None].to(x.device)
            
        if not torch.is_tensor(timesteps_r):
            timesteps_r = torch.tensor([timesteps_r], dtype=torch.long, device=x.device)
        elif torch.is_tensor(timesteps_r) and len(timesteps_r.shape) == 0:
            timesteps_r = timesteps_r[None].to(x.device)

        # Embed timesteps
        t_emb = self.t_embedder(timesteps_t)  # (N, D)
        delta_emb = self.delta_embedder(timesteps_r - timesteps_t)
        c = t_emb + delta_emb

        # U-Net style transformer blocks
        skips = []
        for blk in self.in_blocks:
            x = blk(x, c, token_mask=token_mask)
            skips.append(x)

        x = self.mid_block(x, c, token_mask=token_mask)

        for blk in self.out_blocks:
            x = blk(x, c, skips.pop(), token_mask=token_mask)

        x = self.final_layer(x, c)  # (N, T, output_dim)
        
        # Project back to output format: (N, T, D) -> (N, D, T)
        x = x.transpose(2, 1)
        
        # Remove the fixed enrollment and mixture condition portions.
        x = x[:, :, enrollment_length + mixture_length:]
        if state_mask is not None:
            x = x.masked_fill(~state_mask[:, None], 0)
        
        return x


